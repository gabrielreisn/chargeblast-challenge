export type RouteKey = keyof typeof routes;

// Metadata is merged shallowly between segments, so nested objects that child
// routes override (openGraph, twitter) must spread these shared defaults.
/** Generated by `app/opengraph-image.tsx`, which reads its size and alt text from here. */
export const ogImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: site.title,
  type: "image/png",
} as const;

const sharedOpenGraph = {
  type: "website",
  siteName: site.name,
  locale: site.locale,
  images: [ogImage],
} satisfies Metadata["openGraph"];

const sharedTwitter = {
  card: "summary_large_image",
  images: [ogImage],
} satisfies Metadata["twitter"];

export const rootMetadata: Metadata = {
  metadataBase: siteUrl(),
  title: { default: site.title, template: `%s · ${site.name}` },
  description: site.description,
  applicationName: site.name,
  openGraph: { ...sharedOpenGraph, title: site.title, description: site.description },
  twitter: { ...sharedTwitter, title: site.title, description: site.description },
  robots: { index: true, follow: true },
  formatDetection: { telephone: false, email: false, address: false },
};

export const viewport: Viewport = {
  themeColor: site.themeColor,
  colorScheme: "light",
};

/** Metadata for a public route: title, description, canonical and social cards. */
export function routeMetadata(key: RouteKey): Metadata {
  const { path, title, description } = routes[key];
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: { ...sharedOpenGraph, title: `${title} · ${site.name}`, description, url: path },
    twitter: { ...sharedTwitter, title: `${title} · ${site.name}`, description },
  };
}

/** Pages that exist for people but must stay out of search results (record details, errors). */
export function privateMetadata(title: string): Metadata {
  return { title, robots: { index: false, follow: false } };
}

export function sitemapEntries(): MetadataRoute.Sitemap {
  const origin = siteUrl();
  return Object.values(routes).map((route) => ({
    url: new URL(route.path, origin).toString(),
    changeFrequency: route.changeFrequency,
    priority: route.priority,
  }));
}

export function robotsRules(): MetadataRoute.Robots {
  return {
    rules: { userAgent: "*", allow: "/", disallow: ["/api/"] },
    sitemap: new URL("/sitemap.xml", siteUrl()).toString(),
    host: siteUrl().origin,
  };
}

export function webManifest(): MetadataRoute.Manifest {
  return {
    name: site.title,
    short_name: site.name,
    description: site.description,
    start_url: routes.payments.path,
    display: "standalone",
    background_color: site.backgroundColor,
    theme_color: site.themeColor,
    icons: [{ src: "/favicon.ico", sizes: "any", type: "image/x-icon" }],
  };
}
